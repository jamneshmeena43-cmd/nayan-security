export function discountPercent(p) {
  if (!p.mrp || p.mrp <= p.price) return 0;
  return Math.round((1 - p.price / p.mrp) * 100);
}

export function stockLabel(p) {
  if (p.stock <= 0) return { key: "out", text: "Out of stock · sample catalog" };
  if (p.stock <= 3) return { key: "low", text: `Low stock · ${p.stock} in sample catalog` };
  return { key: "ok", text: "In stock · sample catalog" };
}

