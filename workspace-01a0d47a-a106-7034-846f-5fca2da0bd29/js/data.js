export function searchAll(q) {
  const s = q.trim().toLowerCase();
  if (!s) return { products: [], services: [], professionals: [], shops: [] };
  const hit = (...parts) => parts.filter(Boolean).join(" ").toLowerCase().includes(s);
  return {
    products: products.filter((p) => hit(p.name, p.brand, p.model, p.description, p.categories.join(" "))),
    services: services.filter((sv) => hit(sv.name, sv.short, sv.description)),
    professionals: professionals.filter((p) => hit(p.name, p.business, p.area, p.bio)),
    shops: shops.filter((sh) => hit(sh.name, sh.area, sh.about, sh.productsNote)),
  };
}
